import { readFile, writeFile } from 'node:fs/promises';
const names = ['PaymentRouter','SubscriptionManager','RewardsVault','PartnershipRegistry','OffersRedemption'];
let source = '// Generated by npm run contracts:build. Do not edit.\n';
for (const name of names) {
 const artifact = JSON.parse(await readFile(`contracts/out/${name}.sol/${name}.json`,'utf8'));
 source += `export const ${name[0].toLowerCase()+name.slice(1)}Abi = ${JSON.stringify(artifact.abi)} as const;\n`;
}
await writeFile('packages/chain/abi.ts',source);
